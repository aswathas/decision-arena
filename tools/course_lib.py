"""Shared helpers for the Decision Arena Academy course files.

Stdlib only, no network. This module is the single source of truth for:

  * the front-matter format of ``course/lessons/<id>-<slug>.md``
  * the generated index ``course/curriculum.json``
  * the quiz format ``course/quizzes/<id>.json``
  * where learner progress lives (``learning/progress.json``)

The lesson markdown files are the source of truth. ``curriculum.json`` is
GENERATED by ``tools/course_check.py --index`` and is committed so that agents
can read the whole course shape in one file without parsing markdown. If the
two disagree, ``course_check.py --check`` fails.

Costs: pure file IO. Every function returns plain dicts/lists.
"""
