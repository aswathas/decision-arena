# ------------------------------------------------------------ front matter
def _parse_scalar(raw: str):
    """Turn a front-matter value into a python object.

    Supports: inline lists [a, b], quoted strings, booleans, integers, plain
    strings. Returns the raw stripped string for anything else.
    """
    raw = raw.strip()
    if raw.startswith("[") and raw.endswith("]"):
        inner = raw[1:-1].strip()
        if not inner:
            return []
        return [p.strip().strip('"').strip("'") for p in inner.split(",") if p.strip()]
    if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in "\"'":
        return raw[1:-1]
    low = raw.lower()
    if low == "true":
        return True
    if low == "false":
        return False
    if re.fullmatch(r"-?\d+", raw):
        return int(raw)
    return raw


def parse_frontmatter(text: str):
    """Split a lesson file into (metadata dict, body str).

    Raises ValueError when the front matter is missing or malformed - a broken
    lesson file must fail loudly, not teach the wrong thing.
    """
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError("missing front matter (file must start with '---')")
    end = None
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            end = i
            break
    if end is None:
        raise ValueError("unterminated front matter (no closing '---')")

    meta = {}
    i = 1
    while i < end:
        line = lines[i]
        if not line.strip() or line.startswith((" ", "\t")):
            i += 1
            continue
        if ":" not in line:
            raise ValueError("bad front-matter line: %r" % line)
        key, _, raw = line.partition(":")
        key = key.strip()
        raw = raw.strip()
        if raw == ">":
            buf = []
            j = i + 1
            while j < end and (not lines[j].strip() or lines[j].startswith((" ", "\t"))):
                buf.append(lines[j].strip())
                j += 1
            meta[key] = " ".join(x for x in buf if x).strip()
            i = j
            continue
        if raw == "":
            items = []
            j = i + 1
            while j < end and lines[j].strip().startswith("- "):
                items.append(lines[j].strip()[2:].strip())
                j += 1
            meta[key] = items
            i = j
            continue
        meta[key] = _parse_scalar(raw)
        i += 1

    return meta, "\n".join(lines[end + 1:])


def parse_sections(body: str) -> dict:
    """Split a lesson body into {section title: text} on '## ' headings."""
    sections = {}
    current = None
    buf = []
    for line in body.splitlines():
        if line.startswith("## "):
            if current is not None:
                sections[current] = "\n".join(buf).strip()
            current = line[3:].strip()
            buf = []
        elif current is not None:
            buf.append(line)
    if current is not None:
        sections[current] = "\n".join(buf).strip()
    return sections


# ------------------------------------------------------------------ lessons
def lesson_files() -> list:
    """Absolute paths of every lesson file, in phase/id order."""
    if not os.path.isdir(LESSONS_DIR):
        return []
    names = [n for n in os.listdir(LESSONS_DIR) if n.endswith(".md")]
    names.sort()
    return [os.path.join(LESSONS_DIR, n) for n in names]


def load_lessons() -> list:
    """Load every lesson file into a dict of metadata plus _sections/_file.

    Returns a list ordered by (phase, filename). Raises ValueError on a file
    that cannot be parsed.
    """
    out = []
    for path in lesson_files():
        with open(path, "r", encoding="utf-8") as f:
            text = f.read()
        meta, body = parse_frontmatter(text)
        meta["_file"] = path
        meta["_rel"] = os.path.relpath(path, REPO_ROOT).replace("\\", "/")
        meta["_sections"] = parse_sections(body)
        meta["_body"] = body
        out.append(meta)
    out.sort(key=lambda m: (int(m.get("phase", 0)),
                             int(m.get("order", 999)),
                             os.path.basename(m["_file"])))
    return out


def lesson_by_id(lessons: list, lesson_id: str):
    """Find one lesson by id (case-insensitive). Returns None when missing."""
    for m in lessons:
        if str(m.get("id", "")).lower() == lesson_id.lower():
            return m
    return None


# -------------------------------------------------------------------- quiz
def load_quiz(lesson_id: str) -> dict:
    """Load the quiz for a lesson id from course/quizzes/<id>.json.

    Returns {"lesson_id", "questions": [...]} or raises FileNotFoundError.
    """
    path = os.path.join(QUIZZES_DIR, "%s.json" % lesson_id)
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def quiz_ids() -> list:
    if not os.path.isdir(QUIZZES_DIR):
        return []
    return sorted(n[:-5] for n in os.listdir(QUIZZES_DIR) if n.endswith(".json"))


# ------------------------------------------------------------------ index
def build_index() -> dict:
    """Build the curriculum index dict from the lesson files.

    Shape:
        {"generated_from": "course/lessons",
         "paths": [{"id","label","lessons":[ids]}],
         "phases": [{"id","title","lessons":[{id,title,minutes,...}]}]}
    """
    lessons = load_lessons()
    phases = []
    by_phase = {}
    for m in lessons:
        by_phase.setdefault(int(m["phase"]), []).append(m)

    for pid in sorted(by_phase):
        rows = []
        for m in by_phase[pid]:
            rows.append({
                "id": m["id"],
                "title": m["title"],
                "minutes": m.get("minutes"),
                "order": m.get("order"),
                "concepts": m.get("concepts", []),
                "prereqs": m.get("prereqs", []),
                "paths": m.get("paths", []),
                "exercise_file": m.get("exercise_file"),
                "quiz": m.get("quiz"),
                "file": m["_rel"],
            })
        phases.append({
            "id": pid,
            "title": PHASE_TITLES.get(pid, "Phase %s" % pid),
            "lessons": rows,
        })

    paths = []
    for pname in PATH_ORDER:
        ids = [m["id"] for m in lessons if pname in (m.get("paths") or [])]
        paths.append({"id": pname, "label": PATH_LABELS.get(pname, pname),
                      "lessons": ids})

    return {
        "generated_from": "course/lessons",
        "total_lessons": len(lessons),
        "paths": paths,
        "phases": phases,
    }


def write_index(path: str = CURRICULUM_PATH) -> str:
    """Write the generated index to disk. Returns the path written."""
    index = build_index()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(index, f, indent=2, ensure_ascii=False)
        f.write("\n")
    return path


# --------------------------------------------------------------- progress
def empty_progress(learner: str = "learner", path: str = "beginner") -> dict:
    """A fresh progress document. Timestamps are filled by the caller."""
    return {
        "version": 1,
        "learner": learner,
        "path": path,
        "created_at": None,
        "updated_at": None,
        "lessons": {},
        "concepts": {},
        "review_queue": [],
        "sessions": [],
        "artifacts": [],
    }


def load_progress(path: str = PROGRESS_PATH) -> dict:
    """Load learner progress. Returns None when the learner has not started."""
    if not os.path.exists(path):
        return None
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def save_progress(doc: dict, path: str = PROGRESS_PATH) -> str:
    """Write learner progress to disk. Returns the path written."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(doc, f, indent=2, ensure_ascii=False)
        f.write("\n")
    return path
